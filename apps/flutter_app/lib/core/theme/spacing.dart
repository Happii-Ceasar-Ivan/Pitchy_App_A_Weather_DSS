// Spacing scale: one 4/8 rhythm for all layout gaps, insets and padding.
//
// Use these instead of numeric literals. 2 is allowed only for micro gaps
// inside pills and badges and between a line and its sub-line. 1 (hairline)
// and 0 stay literal.

abstract final class PitchySpace {
  static const xxs = 2.0;
  static const xs = 4.0;
  static const sm = 8.0;
  static const md = 12.0;
  static const lg = 16.0;
  static const xl = 24.0;
  static const xxl = 32.0;
  static const xxxl = 48.0;
}
